/** A deterministic wavy series around `base` (no Math.random, so renders are stable). */
export function series(base: number, swing: number, count = 60, phase = 0): number[] {
  return Array.from({ length: count }, (_, i) =>
    Math.max(
      0,
      base + swing * Math.sin((i + phase) / 3.1) + (swing / 2) * Math.sin((i + phase) * 1.7),
    ),
  );
}

