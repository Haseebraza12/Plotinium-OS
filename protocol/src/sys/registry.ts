export type Calls = typeof CALLS;
export type ArgsIn<C extends CallName> = v.InferInput<Calls[C]['args']>;
export type ArgsOf<C extends CallName> = v.InferOutput<Calls[C]['args']>;
export type RetOf<C extends CallName> = v.InferOutput<Calls[C]['ret']>;

/** The registry entry of a call name, or undefined for an unknown name (stage 2 → ENOSYS). */
export function lookupCall(name: string): CallSpec | undefined {
  return Object.hasOwn(CALLS, name) ? (CALLS as Record<string, CallSpec>)[name] : undefined;
}

/**
 * The dispatch table of one port origin (§3.3 stage 2): E for executor ports, V for view ports.
 * With `ai: false` (the AI-off build, C12) every `ai.*` name is absent and answers ENOSYS.
 */
export function callTable(
  origin: 'E' | 'V',
  options: { ai: boolean },
): ReadonlyMap<CallName, CallSpec> {
  const table = new Map<CallName, CallSpec>();
  for (const name of CALL_NAMES) {
    const spec: CallSpec = CALLS[name];
    if (!options.ai && isAiCall(name)) continue;
    if (spec.origin === 'EV' || spec.origin === origin) table.set(name, spec);
  }
  return table;
}

/**
 * Capabilities a caller needs at stage 4 for these parsed arguments. Cross-uid capabilities
 * (`capsCrossUid`) are checked at stage 5 and are not included.
 */
export function requiredCaps(
  spec: CallSpec,
  args: unknown,
  callerClass: ProcClass,
): readonly Cap[] {
  const base = callerClass === 'agent' && spec.capsAgent !== undefined ? spec.capsAgent : spec.caps;
  const extra = spec.capsFor?.(args) ?? [];
  return extra.length === 0 ? base : [...new Set([...base, ...extra])];
}
