/**
 * The call registry (syscall-abi.md §3.11 and §4.4, ABI-11).
 *
 * One entry per system call, with its argument and return schemas, class, origin set, required
 * capabilities, audit level, call-specific errno list and `man 2` summary. The ABI-11 conformance
 * test parses the catalogue tables of syscall-abi.md §4.4 and compares them with this object, so
 * the spec and the code cannot drift apart silently.
 *
 * Field conventions beyond §3.11's `CallSpec` sketch (needed to express the catalogue exactly):
 * - `clsAlt`: the second class of cells such as "F; T when `create` or `trunc` changes something".
 * - `capsDynamic` + `capsFor(args)`: capabilities that depend on the parsed arguments (stage 4),
 *   for example `open` needs `fs.write` unless `flags` is `'r'`.
 * - `capsAgent`: replaces `caps` for agent-class callers (`batch` needs `batch.grant`, §5.4).
 * - `capsCrossUid`: evaluated at stage 5 when the target belongs to another uid (`kill.other`).
 * - `audit`: 'conditional' marks the "S if …, else T" cells; 'agent' marks the agent-only calls;
 *   'none' marks `tty.input` (keystrokes are never logged).
 * - `may`: the call exists only if its MAY requirement is built (`link`, `mmap`, `ai.undo`, …).
 * Stage 1–4 errnos (ESRCH, ENOSYS, EINVAL, ENAMETOOLONG, EPERM) are implicit for every call.
 */
