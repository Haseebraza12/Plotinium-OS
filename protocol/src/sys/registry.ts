export type CallClass = 'F' | 'T' | 'B' | 'X' | 'R';
export type CallOrigin = 'E' | 'V' | 'EV';
export type CallAudit = 'none' | 'trace' | 'security' | 'conditional' | 'agent';
export type CallGroup =
  'proc' | 'fs' | 'fd' | 'tty' | 'win' | 'mem' | 'time' | 'lock' | 'net' | 'ev' | 'ai' | 'sys';

export interface CallSpec {
  readonly group: CallGroup;
  readonly args: v.GenericSchema;
  readonly ret: v.GenericSchema;
  readonly cls: CallClass;
  readonly clsAlt?: CallClass;
  readonly origin: CallOrigin;
  /** Always required at stage 4. */
  readonly caps: readonly Cap[];
  /** Every capability `capsFor` may add. */
  readonly capsDynamic?: readonly Cap[];
  /** Capabilities required by these (already parsed) arguments, in addition to `caps`. */
  capsFor?(args: unknown): readonly Cap[];
  /** Replaces `caps` for agent-class callers. */
  readonly capsAgent?: readonly Cap[];
  /** Required at stage 5 when the target belongs to another uid. */
  readonly capsCrossUid?: readonly Cap[];
  readonly audit: CallAudit;
  /** Allowed above 64 KiB of non-binary arguments (up to 1 MiB, §3.1 rule 3). */
  readonly large?: true;
  /** Built only if the corresponding MAY requirement is implemented. */
  readonly may?: true;
  /** Call-specific errnos; the stage 1–4 errnos are implicit. */
  readonly errnos: readonly Errno[];
  /** One-line summary; the `man 2` page is generated from it. */
  readonly man: string;
}

const openCaps = (args: unknown): readonly Cap[] => {
  const a = args as fs.OpenArgs;
  const caps = new Set<Cap>();
  if (a.flags === 'r' || a.flags === 'rw') caps.add('fs.read');
  if (a.flags !== 'r' || a.create === true || a.trunc === true) caps.add('fs.write');
  return [...caps];
};
const mmapCaps = (args: unknown): readonly Cap[] =>
  (args as v.InferOutput<typeof mem.MmapArgs>).flags === 'rw' ? ['fs.write'] : [];
const fsckCaps = (args: unknown): readonly Cap[] =>
  (args as v.InferOutput<typeof sys.FsckArgs>).repair === true ? ['sys.admin'] : [];
const indexStatusCaps = (args: unknown): readonly Cap[] =>
  (args as v.InferOutput<typeof rag.IndexStatusArgs>).files === true ? ['ai.index'] : [];
const sysctlSetCaps = (args: unknown): readonly Cap[] =>
  sys.isSessionSysctlKey((args as v.InferOutput<typeof sys.SysctlSetArgs>).key)
    ? []
    : ['sys.admin'];

