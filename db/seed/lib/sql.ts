/**
 * Renders BenchData as one SQL script (database.md §3.27 load method): multi-row INSERTs in
 * batches, ONE transaction for the whole load, then set-based fix-ups (directory nlink, blob
 * refcounts, users.used_*), so the integrity probes are clean afterwards. The script uses no psql
 * meta-commands, so it runs through psql and through node-postgres alike. VACUUM (ANALYZE) is
 * emitted after COMMIT unless disabled: it cannot run inside a transaction or a multi-statement
 * string, so a node-postgres runner sends it separately.
 */
import {
  HOME_INO,
  ROOT_INO,
  TEAM_GID,
  USERS_GID,
  type BenchData,
  type SeedBlob,
  type SeedDentry,
  type SeedInode,
  type SeedUser,
} from './generate.ts';

export const BATCH_ROWS = 1000;
/** Bench users are quota-rich: the benchmark measures queries, not quota refusals. */
const BENCH_QUOTA_BYTES = 100 * 1024 ** 3;
const BENCH_QUOTA_INODES = 1_000_000;

/** A SQL string literal (standard_conforming_strings = on: only the quote is doubled). */
export function lit(s: string): string {
  if (s.includes('\0')) throw new Error('NUL in a SQL literal');
  return `'${s.replaceAll("'", "''")}'`;
}

const bytea = (hex: string): string => `'\\x${hex}'::bytea`;
const ts = (ms: number): string => `'${new Date(ms).toISOString()}'::timestamptz`;
const storageKey = (sha: string): string =>
  `blobs/sha256/${sha.slice(0, 2)}/${sha.slice(2, 4)}/${sha}`;

function batched<T>(
  rows: readonly T[],
  head: string,
  render: (row: T) => string,
  tail = '',
): string[] {
  const out: string[] = [];
  for (let i = 0; i < rows.length; i += BATCH_ROWS) {
    const values = rows
      .slice(i, i + BATCH_ROWS)
      .map(render)
      .join(',\n  ');
    out.push(`${head}\n  ${values}${tail};`);
  }
  return out;
}

export interface RenderOptions {
  /** Append VACUUM (ANALYZE) after COMMIT (default true). */
  readonly vacuum?: boolean;
}

export function renderBenchSql(data: BenchData, options: RenderOptions = {}): string {
  const m = data.manifest;
  const parts: string[] = [
    `-- Plotinium bench seed: profile ${m.profile}, mulberry32 seed ${m.seed}.`,
    '-- Generated by db/seed/seed.ts (database.md §3.27). Do not edit; regenerate.',
    `-- Adds ${m.newInodes} inodes: ${m.totalInodes} in total on a freshly migrated database.`,
    'BEGIN;',
    `DO $$ BEGIN
  IF NOT EXISTS (SELECT 1 FROM inodes WHERE ino = ${lit(ROOT_INO)}) THEN
    RAISE EXCEPTION 'the well-known root inode is missing: run the migrations first';
  END IF;
  IF EXISTS (SELECT 1 FROM users WHERE uid BETWEEN 1001 AND 1059) THEN
    RAISE EXCEPTION 'the bench seed is already loaded (users 1001-1059 exist)';
  END IF;
END $$;`,
    `INSERT INTO groups (gid, name) VALUES (${TEAM_GID}, 'team') ON CONFLICT (gid) DO NOTHING;`,
    ...batched(
      data.users,
      'INSERT INTO users (uid, username, account_kind, password_hash, primary_gid, quota_bytes, quota_inodes) VALUES',
      // '!' is a locked password: bench accounts cannot log in (C10: no known credentials).
      (u: SeedUser) =>
        `(${u.uid}, ${lit(u.username)}, 'user', '!', ${USERS_GID}, ${BENCH_QUOTA_BYTES}, ${BENCH_QUOTA_INODES})`,
    ),
  ];
  const memberships = data.users.flatMap((u) => u.groups.map((gid) => ({ uid: u.uid, gid })));
  if (memberships.length > 0) {
    parts.push(
      ...batched(
        memberships,
        'INSERT INTO user_groups (uid, gid) VALUES',
        (r) => `(${r.uid}, ${r.gid})`,
      ),
    );
  }
  parts.push(
    ...batched(
      data.blobs,
      'INSERT INTO blobs (sha256, size, storage_key) VALUES',
      (b: SeedBlob) => `(${bytea(b.sha)}, ${b.size}, ${lit(storageKey(b.sha))})`,
    ),
    `CREATE TEMP TABLE seed_inodes (
  ino uuid PRIMARY KEY, type text, mode smallint, uid integer, gid integer, size bigint,
  blob_sha bytea, mtime timestamptz
) ON COMMIT DROP;`,
    ...batched(
      data.inodes,
      'INSERT INTO seed_inodes (ino, type, mode, uid, gid, size, blob_sha, mtime) VALUES',
      (n: SeedInode) =>
        `(${lit(n.ino)}, '${n.type}', ${n.mode}, ${n.uid}, ${n.gid}, ${n.size}, ${
          n.blobSha === null ? 'NULL' : bytea(n.blobSha)
        }, ${ts(n.mtimeMs)})`,
    ),
    `INSERT INTO inodes (ino, type, mode, uid, gid, size, nlink, blob_id, created_at, modified_at, changed_at, accessed_at)
SELECT s.ino, s.type, s.mode, s.uid, s.gid, s.size, CASE WHEN s.type = 'd' THEN 2 ELSE 1 END, b.blob_id,
       s.mtime, s.mtime, s.mtime, s.mtime
FROM seed_inodes s LEFT JOIN blobs b ON b.sha256 = s.blob_sha
ORDER BY s.ino;`,
    ...batched(
      data.dentries,
      'INSERT INTO dentries (parent_ino, name, ino, d_type, owner_uid) VALUES',
      (d: SeedDentry) =>
        `(${lit(d.parent)}, ${lit(d.name)}, ${lit(d.ino)}, '${d.dType}', ${d.ownerUid})`,
    ),
    '-- Set-based fix-ups (database.md §3.27): the probes must be clean before the manifest is written.',
    `UPDATE inodes i SET nlink = 2 + c.n
FROM (SELECT parent_ino, count(*) AS n FROM dentries WHERE d_type = 'd' GROUP BY parent_ino) c
WHERE i.ino = c.parent_ino AND i.type = 'd' AND i.nlink <> 2 + c.n;`,
    `UPDATE inodes SET version = version + 1, modified_at = now(), changed_at = now() WHERE ino = ${lit(HOME_INO)};`,
    `UPDATE blobs b SET refcount = r.n, zero_since = NULL, first_ref_at = coalesce(b.first_ref_at, now())
FROM (SELECT blob_id, count(*) AS n FROM inodes WHERE blob_id IS NOT NULL GROUP BY blob_id) r
WHERE b.blob_id = r.blob_id;`,
    `UPDATE users u SET used_bytes = a.bytes, used_inodes = a.n
FROM (SELECT uid, coalesce(sum(size), 0) AS bytes, count(*) AS n FROM inodes GROUP BY uid) a
WHERE u.uid = a.uid AND (u.used_bytes <> a.bytes OR u.used_inodes <> a.n);`,
    'COMMIT;',
  );
  if (options.vacuum !== false) parts.push('VACUUM (ANALYZE);');
  return `${parts.join('\n')}\n`;
}
