-- Plotinium OS: DB prototype schema (PostgreSQL 18.6 + pgvector 0.8.6)
-- Database created with: --locale-provider=builtin --builtin-locale=C.UTF-8
DROP SCHEMA IF EXISTS vfs CASCADE;
CREATE SCHEMA vfs;
SET search_path = vfs, public;
CREATE EXTENSION IF NOT EXISTS vector;
CREATE EXTENSION IF NOT EXISTS pg_trgm;

CREATE TABLE groups (
  gid   integer PRIMARY KEY,
  name  text NOT NULL UNIQUE
);

CREATE TABLE users (
  uid           integer PRIMARY KEY,
  username      text NOT NULL UNIQUE CHECK (username ~ '^[a-z_][a-z0-9_-]{0,31}$'),
  password_hash text NOT NULL,
  primary_gid   integer NOT NULL REFERENCES groups,
  quota_bytes   bigint NOT NULL CHECK (quota_bytes  >= 0),
  quota_inodes  bigint NOT NULL CHECK (quota_inodes >= 0),
  used_bytes    bigint NOT NULL DEFAULT 0,
  used_inodes   bigint NOT NULL DEFAULT 0,
  -- quota is a database invariant: an UPDATE that would exceed it fails (SQLSTATE 23514 -> EDQUOT)
  CONSTRAINT quota_bytes_ok  CHECK (used_bytes  BETWEEN 0 AND quota_bytes),
  CONSTRAINT quota_inodes_ok CHECK (used_inodes BETWEEN 0 AND quota_inodes)
);

CREATE TABLE user_groups (
  uid integer NOT NULL REFERENCES users ON DELETE CASCADE,
  gid integer NOT NULL REFERENCES groups ON DELETE CASCADE,
  PRIMARY KEY (uid, gid)
);

CREATE TABLE blobs (
  blob_id     bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  sha256      bytea  NOT NULL CHECK (octet_length(sha256) = 32),
  size        bigint NOT NULL CHECK (size >= 0),
  storage_key text   NOT NULL,
  refcount    integer NOT NULL CHECK (refcount >= 0),
  -- uniqueness enforced through a HASH index (B-tree is the only AM allowed for UNIQUE, EXCLUDE works with hash)
  CONSTRAINT blobs_sha256_uniq EXCLUDE USING hash (sha256 WITH =)
);

CREATE TABLE inodes (
  ino            uuid PRIMARY KEY DEFAULT uuidv7(),
  type           "char" NOT NULL CHECK (type IN ('f','d','l')),
  mode           smallint NOT NULL CHECK (mode BETWEEN 0 AND 1023),      -- rwxrwxrwx + sticky (0o1000)
  uid            integer NOT NULL REFERENCES users,
  gid            integer NOT NULL REFERENCES groups,
  size           bigint  NOT NULL DEFAULT 0 CHECK (size >= 0),
  nlink          integer NOT NULL DEFAULT 1 CHECK (nlink >= 0),
  version        bigint  NOT NULL DEFAULT 1 CHECK (version >= 1),
  blob_id        bigint REFERENCES blobs,
  symlink_target text CHECK (octet_length(symlink_target) <= 4096),
  created_at     timestamptz NOT NULL DEFAULT now(),
  modified_at    timestamptz NOT NULL DEFAULT now(),
  changed_at     timestamptz NOT NULL DEFAULT now(),
  accessed_at    timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT symlink_has_target CHECK ((type = 'l') = (symlink_target IS NOT NULL)),
  CONSTRAINT only_files_have_blobs CHECK (type = 'f' OR blob_id IS NULL),
  CONSTRAINT sticky_only_on_dirs CHECK (type = 'd' OR mode < 512),
  CONSTRAINT inodes_ino_type     UNIQUE (ino, type),       -- target of dentry_parent (parent must be 'd')
  CONSTRAINT inodes_ino_type_uid UNIQUE (ino, type, uid)   -- target of dentry_child (type + owner copy)
);

CREATE TABLE dentries (
  parent_ino  uuid   NOT NULL,
  parent_type "char" NOT NULL DEFAULT 'd' CHECK (parent_type = 'd'),   -- parent must be a directory
  name        text   NOT NULL COLLATE "C"
              CHECK (name <> '' AND name NOT IN ('.', '..') AND strpos(name, '/') = 0
                     AND octet_length(name) <= 255),
  ino         uuid   NOT NULL,
  d_type      "char" NOT NULL,
  owner_uid   integer NOT NULL,          -- denormalised copy of inodes.uid, kept equal by the FK cascade
  CONSTRAINT dentries_pk PRIMARY KEY (parent_ino, name) INCLUDE (ino, d_type),
  CONSTRAINT dentry_child  FOREIGN KEY (ino, d_type, owner_uid)
             REFERENCES inodes (ino, type, uid) ON UPDATE CASCADE,
  CONSTRAINT dentry_parent FOREIGN KEY (parent_ino, parent_type)
             REFERENCES inodes (ino, type)
);
-- a directory has exactly one name (no hard links to directories); also the index for the ancestor walk
CREATE UNIQUE INDEX dentries_dir_one_parent ON dentries (ino) WHERE d_type = 'd';
-- reverse lookup for files (hard links, citations, Q4 names)
CREATE INDEX dentries_ino ON dentries (ino);
-- Q3 prefix search on one user's names
CREATE INDEX dentries_owner_lname ON dentries (owner_uid, lower(name) text_pattern_ops);
-- Q4 recent files
CREATE INDEX inodes_uid_mtime ON inodes (uid, modified_at DESC);

CREATE TABLE file_chunks (
  chunk_id     bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  ino          uuid NOT NULL REFERENCES inodes ON DELETE CASCADE,
  seq          integer NOT NULL,
  line_start   integer NOT NULL,
  text         text NOT NULL,
  content_hash bytea NOT NULL,
  embedding    vector(384) NOT NULL,
  UNIQUE (ino, seq)
);

CREATE TABLE op_log (
  op_id      uuid PRIMARY KEY,               -- idempotency key generated by the client
  uid        integer NOT NULL REFERENCES users,
  session_id uuid NOT NULL,
  op         text NOT NULL,
  payload    jsonb NOT NULL,
  result     jsonb,
  applied_at timestamptz NOT NULL DEFAULT now()
);

-- ---------------------------------------------------------------- test-only fault hook
CREATE FUNCTION fault_hook() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE
  n int := nullif(current_setting('plotinium.fault_after', true), '')::int;
  c int;
BEGIN
  IF n IS NOT NULL THEN
    c := coalesce(nullif(current_setting('plotinium.fault_count', true), ''), '0')::int + 1;
    PERFORM set_config('plotinium.fault_count', c::text, true);
    IF c > n THEN
      RAISE EXCEPTION 'injected fault after % node ops', n USING ERRCODE = 'P0001';
    END IF;
  END IF;
  RETURN COALESCE(NEW, OLD);
END $$;
CREATE TRIGGER fault_inodes BEFORE INSERT OR UPDATE OR DELETE ON inodes
  FOR EACH ROW EXECUTE FUNCTION fault_hook();
